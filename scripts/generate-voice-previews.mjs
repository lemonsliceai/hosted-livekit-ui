#!/usr/bin/env node
// Generates one preview clip per voice listed in src/ui/PreCallSetup.tsx with the Fish Audio TTS API,
// uploads them to the public Vercel Blob store, and writes src/ui/sounds/voices/index.ts with the URLs.
//
// Usage:
//   FISH_API_KEY=... BLOB_READ_WRITE_TOKEN=... node scripts/generate-voice-previews.mjs
//   Add --force to regenerate clips that already exist, and --no-upload to skip the blob step.
//
// Clips are kept in scripts/voice-previews/ (gitignored) and are never bundled into the package.

import { access, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const TEXT = "Hey! This is an example of how I'll be in the realtime video call. What do you think?";
const MODEL = "s2-pro";
const FORMAT = "mp3";
const MP3_BITRATE = 64;
const BLOB_PREFIX = "hosted-call/voice-previews";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const voicesSource = path.join(root, "src/ui/PreCallSetup.tsx");
const clipDir = path.join(root, "scripts/voice-previews");
const indexFile = path.join(root, "src/ui/sounds/voices/index.ts");

const args = new Set(process.argv.slice(2));
const force = args.has("--force");
const upload = !args.has("--no-upload");

const apiKey = process.env.FISH_API_KEY;
if (!apiKey) {
  console.error("FISH_API_KEY is not set.");
  process.exit(1);
}
const blobToken = process.env.BLOB_READ_WRITE_TOKEN;
if (upload && !blobToken) {
  console.error("BLOB_READ_WRITE_TOKEN is not set. Pass --no-upload to write clips locally only.");
  process.exit(1);
}

const exists = (file) =>
  access(file).then(
    () => true,
    () => false,
  );

const source = await readFile(voicesSource, "utf8");
const voices = [...source.matchAll(/\{ value: "([0-9a-f]{32})", label: "([^"]+)"/g)].map(
  ([, id, label]) => ({ id, label }),
);
if (voices.length === 0) {
  console.error(`No voices found in ${voicesSource}`);
  process.exit(1);
}

await mkdir(clipDir, { recursive: true });

for (const { id, label } of voices) {
  const file = path.join(clipDir, `${id}.mp3`);
  if (!force && (await exists(file))) {
    console.log(`skip   ${label} (${id})`);
    continue;
  }
  const res = await fetch("https://api.fish.audio/v1/tts", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "Content-Type": "application/json",
      model: MODEL,
    },
    body: JSON.stringify({
      text: TEXT,
      reference_id: id,
      format: FORMAT,
      mp3_bitrate: MP3_BITRATE,
      normalize: true,
    }),
  });
  if (!res.ok) {
    throw new Error(`${label} (${id}): ${res.status} ${await res.text()}`);
  }
  await writeFile(file, Buffer.from(await res.arrayBuffer()));
  console.log(`wrote  ${label} (${id})`);
}

const urls = {};
if (upload) {
  // Loaded here so local-only runs don't need the SDK installed.
  const { put } = await import("@vercel/blob");
  for (const { id, label } of voices) {
    const file = path.join(clipDir, `${id}.mp3`);
    if (!(await exists(file))) continue;
    const blob = await put(`${BLOB_PREFIX}/${id}.mp3`, await readFile(file), {
      access: "public",
      contentType: "audio/mpeg",
      addRandomSuffix: false,
      allowOverwrite: true,
      token: blobToken,
    });
    urls[id] = blob.url;
    console.log(`upload ${label} (${id})`);
  }
}

const entries = Object.entries(urls)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, url]) => `  "${id}": "${url}",`)
  .join("\n");

if (upload) {
  await writeFile(
    indexFile,
    `// Generated by scripts/generate-voice-previews.mjs. Do not edit by hand.
// Clips are served from the public Vercel Blob store, not bundled into the package.
export const VOICE_PREVIEWS: Record<string, string> = {
${entries}
};
`,
  );
  console.log(`\n${Object.keys(urls).length} of ${voices.length} voices have previews. Index: ${path.relative(root, indexFile)}`);
} else {
  const count = (await readdir(clipDir)).filter((f) => f.endsWith(".mp3")).length;
  console.log(`\n${count} clips in ${path.relative(root, clipDir)}. Index not changed (--no-upload).`);
}
